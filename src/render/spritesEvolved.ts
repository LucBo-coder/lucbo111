/** Builds a composite of three copies of a sprite in a triangle (Magneton = 3 Magnemite, Dugtrio = 3 Diglett). */
export function composeTrio(rows: string[], gap = 1): string[] {
  const w = Math.max(...rows.map((r) => r.length)), h = rows.length;
  // trim empty rows/cols
  let top = 0, bottom = h - 1, left = w, right = 0;
  while (top < h && !/[^.]/.test(rows[top])) top++;
  while (bottom > top && !/[^.]/.test(rows[bottom])) bottom--;
  for (const r of rows) for (let x = 0; x < r.length; x++) if (r[x] !== '.') { left = Math.min(left, x); right = Math.max(right, x); }
  const t = rows.slice(top, bottom + 1).map((r) => r.padEnd(w, '.').slice(left, right + 1));
  const tw = right - left + 1, th = t.length;
  const W = tw * 2 + gap, H = Math.round(th * 1.7);
  const out = Array.from({ length: H }, () => Array(W).fill('.'));
  const stamp = (ox: number, oy: number) => t.forEach((r, y) => [...r].forEach((c, x) => { if (c !== '.' && oy + y < H) out[oy + y][ox + x] = c; }));
  stamp(Math.floor((W - tw) / 2), 0); // back
  stamp(0, H - th);
  stamp(tw + gap, H - th);
  return out.map((r) => r.join(''));
}
